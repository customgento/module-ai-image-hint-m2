<?php

declare(strict_types=1);

namespace CustomGento\AiImageHint\ViewModel;

use CustomGento\AiImageHint\Model\ResourceModel\AiHint;
use CustomGento\AiImageHint\Model\Source\AiContent;
use CustomGento\AiImageHint\Model\Source\HintColor;
use Magento\Catalog\Api\Data\ProductInterface;
use Magento\Catalog\Helper\Image as ImageHelper;
use Magento\Catalog\Model\Product;
use Magento\Catalog\Model\Product\Configuration\Item\ItemInterface as CartItem;
use Magento\Catalog\Model\Product\Configuration\Item\ItemResolverInterface;
use Magento\Framework\EntityManager\MetadataPool;
use Magento\Framework\Escaper;
use Magento\Framework\View\Asset\Repository as AssetRepository;
use Magento\Framework\View\ConfigInterface as ViewConfig;
use Magento\Framework\View\Element\Block\ArgumentInterface;

/**
 * Looks up the EU AI Act hint (icon + translatable explanation) for a product image.
 */
class AiImageHint implements ArgumentInterface
{
    // "link id|file" => hint, or false for a file we looked up and found no label for
    private array $hints = [];

    public function __construct(
        private readonly AiHint $aiHintResource,
        private readonly ViewConfig $viewConfig,
        private readonly AssetRepository $assets,
        private readonly Escaper $escaper,
        private readonly ItemResolverInterface $itemResolver,
        private readonly MetadataPool $metadataPool,
    ) {
    }

    /**
     * The hint for the two gallery columns as they come off the media gallery row, null when the
     * image carries no label. For callers that already hold the row, so they need no second query.
     */
    public function getHint(int $type, ?string $color): ?array
    {
        if ($type !== AiContent::GENERATED && $type !== AiContent::MODIFIED) {
            return null;
        }

        return [
            'type' => $type,
            'color' => $color === HintColor::WHITE ? HintColor::WHITE : HintColor::BLACK,
            'alt' => (string)($type === AiContent::GENERATED
                ? __('This image was fully generated by artificial intelligence (AI) and is not a real '
                    . 'photograph of the product.')
                : __('This image is based on a real product photograph and was edited using artificial '
                    . 'intelligence (AI).')),
        ];
    }

    /**
     * The hint for a gallery file of a product such as "/a/b/example.jpg", null when the image carries no label.
     */
    public function getHintForFile(Product $product, ?string $file): ?array
    {
        if (!$file || $file === 'no_selection') {
            return null;
        }
        $linkField = $this->metadataPool->getMetadata(ProductInterface::class)->getLinkField();
        $linkFieldValue = (int)$product->getData($linkField);
        $key = $linkFieldValue . '|' . $file;
        if (!array_key_exists($key, $this->hints)) {
            $row = $this->aiHintResource->getByFile($file, $linkField, $linkFieldValue);
            $this->hints[$key] = $row
                ? $this->getHint((int)$row['ai_content'], $row['ai_hint_color']) ?? false
                : false;
        }

        return $this->hints[$key] ?: null;
    }

    /**
     * The hint for the image a product list block renders, addressed by view.xml image id such as
     * "category_page_grid". Resolving the id to an image attribute is what core's Block\Product\
     * ImageFactory does, so the file we look up is the one that was actually rendered.
     */
    public function getHintForProductImage(Product $product, string $imageId): ?array
    {
        $mediaAttributes = $this->viewConfig->getViewConfig()->getMediaAttributes(
            'Magento_Catalog',
            ImageHelper::MEDIA_TYPE_CONFIG_NODE,
            $imageId
        );

        return isset($mediaAttributes['type'])
            ? $this->getHintForFile($product, (string)$product->getData($mediaAttributes['type']))
            : null;
    }

    /**
     * The small AI mark, ready to drop into any template: <?= $aiImageHint->getBadgeHtml($hint) ?>
     */
    public function getBadgeHtml(?array $hint): string
    {
        if (!$hint) {
            return '';
        }
        $alt = $this->escaper->escapeHtmlAttr($hint['alt']);

        return sprintf(
            '<img src="%s" alt="%s" title="%2$s" loading="lazy" class="ai-image-hint"/>',
            $this->escaper->escapeUrl($this->iconUrl('ai-mark', $hint['color'])),
            $alt
        );
    }

    /**
     * Both icon sizes for one hint, for the Alpine driven product page gallery.
     */
    public function getIconUrls(array $hint): array
    {
        $full = $hint['type'] === AiContent::GENERATED ? 'ai-generated' : 'ai-modified';

        return [
            'full' => $this->iconUrl($full, $hint['color']),
            'mark' => $this->iconUrl('ai-mark', $hint['color']),
        ];
    }

    /**
     * The small AI mark for the thumbnail of a cart item, as JS rendered carts need it: ['icon' => url, 'alt' => text].
     * The item resolver is the one core uses to pick the thumbnail, so the hint belongs to the image actually shown.
     */
    public function getCartItemHint(CartItem $item, string $imageId): ?array
    {
        $product = $this->itemResolver->getFinalProduct($item);
        $hint = $product instanceof Product ? $this->getHintForProductImage($product, $imageId) : null;

        return $hint ? ['icon' => $this->iconUrl('ai-mark', $hint['color']), 'alt' => $hint['alt']] : null;
    }

    private function iconUrl(string $name, string $color): string
    {
        return $this->assets->getUrl(sprintf('CustomGento_AiImageHint::images/ai/%s-%s.svg', $name, $color));
    }
}
