<?php

declare(strict_types=1);

namespace CustomGento\AiImageLabel\Model;

use CustomGento\AiImageLabel\Model\ResourceModel\AiLabel;
use CustomGento\AiImageLabel\Model\Source\AiContent;
use CustomGento\AiImageLabel\Model\Source\LabelColor;
use Magento\Catalog\Api\Data\ProductInterface;
use Magento\Catalog\Helper\Image as ImageHelper;
use Magento\Catalog\Model\Product;
use Magento\Framework\EntityManager\MetadataPool;
use Magento\Framework\Escaper;
use Magento\Framework\View\Asset\Repository as AssetRepository;
use Magento\Framework\View\ConfigInterface as ViewConfig;

/**
 * Looks up the EU AI Act label (icon + translatable explanation) for a product image.
 */
class LabelProvider
{
    // "product link id|file" => label, or false for a file we looked up and found no label for
    private array $labels = [];

    public function __construct(
        private readonly AiLabel $aiLabelResource,
        private readonly ViewConfig $viewConfig,
        private readonly AssetRepository $assets,
        private readonly Escaper $escaper,
        private readonly MetadataPool $metadataPool,
    ) {
    }

    /**
     * The label for the two gallery columns as they come off the media gallery row, null when the
     * image carries no label. For callers that already hold the row, so they need no second query.
     */
    public function getLabel(int $type, ?string $color): ?array
    {
        if ($type !== AiContent::GENERATED && $type !== AiContent::MODIFIED) {
            return null;
        }

        return [
            'type' => $type,
            'color' => $color === LabelColor::WHITE ? LabelColor::WHITE : LabelColor::BLACK,
            'alt' => (string)($type === AiContent::GENERATED
                ? __('This image was fully generated by artificial intelligence (AI) and is not a real '
                    . 'photograph of the product.')
                : __('This image is based on a real product photograph and was edited using artificial '
                    . 'intelligence (AI).')),
        ];
    }

    /**
     * The label for one of the product's gallery files such as "/a/b/example.jpg", null when the image
     * carries no label. The same file can belong to several products, each with its own label.
     */
    public function getLabelForFile(Product $product, ?string $file): ?array
    {
        $linkField = $this->metadataPool->getMetadata(ProductInterface::class)->getLinkField();
        $linkId = (int)$product->getData($linkField);
        if (!$linkId || !$file || $file === 'no_selection') {
            return null;
        }

        $key = $linkId . '|' . $file;
        if (!array_key_exists($key, $this->labels)) {
            $row = $this->aiLabelResource->getByProductFile($linkField, $linkId, $file);
            $this->labels[$key] = $row
                ? $this->getLabel((int)$row['ai_content'], $row['ai_label_color']) ?? false
                : false;
        }

        return $this->labels[$key] ?: null;
    }

    /**
     * The label for the image a product list block renders, addressed by view.xml image id such as
     * "category_page_grid". Resolving the id to an image attribute is what core's Block\Product\
     * ImageFactory does, so the file we look up is the one that was actually rendered.
     */
    public function getLabelForProductImage(Product $product, string $imageId): ?array
    {
        $mediaAttributes = $this->viewConfig->getViewConfig()->getMediaAttributes(
            'Magento_Catalog',
            ImageHelper::MEDIA_TYPE_CONFIG_NODE,
            $imageId
        );

        return isset($mediaAttributes['type'])
            ? $this->getLabelForFile($product, (string)$product->getData($mediaAttributes['type']))
            : null;
    }

    /**
     * The small AI mark as an <img> tag, for server rendered product images.
     */
    public function getBadgeHtml(array $label): string
    {
        $alt = $this->escaper->escapeHtmlAttr($label['alt']);

        return sprintf(
            '<img src="%s" alt="%s" title="%s" loading="lazy" class="ai-image-label"/>',
            $this->escaper->escapeUrl($this->iconUrl('ai-mark', $label['color'])),
            $alt,
            $alt
        );
    }

    /**
     * Both icon sizes for one label, for the product page gallery: labelled icon on the image, mark on its thumbnail.
     */
    public function getIconUrls(array $label): array
    {
        $full = $label['type'] === AiContent::GENERATED ? 'ai-generated' : 'ai-modified';

        return [
            'full' => $this->iconUrl($full, $label['color']),
            'mark' => $this->iconUrl('ai-mark', $label['color']),
        ];
    }

    /**
     * The image url => badge data block ai-image-label.js reads, for gallery images a theme draws in JS.
     * Takes items shaped like the product gallery JSON: thumb/img/full urls plus aiIcon/aiMark/aiAlt.
     */
    public function getBadgeMapHtml(iterable $images): string
    {
        $map = [];
        foreach ($images as $image) {
            if (isset($image['aiIcon'])) {
                $map[$image['thumb']] = ['icon' => $image['aiMark'], 'alt' => $image['aiAlt'], 'size' => 'thumb'];
                $map[$image['img']] = $map[$image['full']]
                    = ['icon' => $image['aiIcon'], 'alt' => $image['aiAlt'], 'size' => 'full'];
            }
        }

        // a data block, not a script, so no CSP nonce is needed; the escaped slashes keep it closed
        return $map
            ? '<script type="application/json" class="ai-image-label-data">'
                . json_encode($map, JSON_THROW_ON_ERROR) . '</script>'
            : '';
    }

    private function iconUrl(string $name, string $color): string
    {
        return $this->assets->getUrl(sprintf('CustomGento_AiImageLabel::images/ai/%s-%s.svg', $name, $color));
    }
}
